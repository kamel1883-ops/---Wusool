/**
 * Bundles migrations/*.sql into worker/lib/schema.ts so a fresh hosted
 * database can be bootstrapped from application code (POST /api/setup/init).
 * Re-run after every migration change: `node scripts/build-schema.mjs`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const dir = join(ROOT, 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

const statements = [];
for (const file of files) {
  const raw = readFileSync(join(dir, file), 'utf8');
  const withoutComments = raw
    .split('\n')
    .filter((line) => !line.trimStart().startsWith('--'))
    .join('\n');
  for (const chunk of withoutComments.split(';')) {
    const sql = chunk.trim();
    if (sql) statements.push(sql);
  }
}

const out = `/**
 * GENERATED by scripts/build-schema.mjs — do not edit by hand.
 * Source: ${files.join(', ')} (${statements.length} statements).
 * Applied idempotently by POST /api/setup/init (CREATE TABLE/INDEX IF NOT
 * EXISTS, INSERT OR IGNORE, UPDATE seeds). ALTER TABLE … ADD COLUMN is
 * retried safely: already-applied columns are skipped by error match.
 */
export const SCHEMA_STATEMENTS: string[] = ${JSON.stringify(statements, null, 2)};
`;
writeFileSync(join(ROOT, 'worker', 'lib', 'schema.ts'), out);
console.log(`wrote worker/lib/schema.ts (${statements.length} statements from ${files.length} files)`);
